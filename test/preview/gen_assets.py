#!/usr/bin/env python3
"""Turns the files under data/ into C arrays named like the console build's bin2o symbols (controller_wiimote.png ->
controller_wiimote_png, controller_wiimote_png_size), plus a stub header for each, so the real menu code links on a host.
usage: gen_assets.py <data dir> <images subdir> <out dir>"""
import os, sys, re

data, images, out = sys.argv[1], sys.argv[2], sys.argv[3]
os.makedirs(os.path.join(out, "stubs"), exist_ok=True)
folders = [images, "fonts", "sounds", "lang"]
names = []
with open(os.path.join(out, "assets.cpp"), "w") as c:
    c.write("// generated by gen_assets.py\n")
    for folder in folders:
        d = os.path.join(data, folder)
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            stem, ext = os.path.splitext(f)
            name = re.sub(r"[^A-Za-z0-9_]", "_", stem) + "_" + ext[1:]
            raw = open(os.path.join(d, f), "rb").read()
            if folder == "sounds":
                raw = b"\0"            # not played on a host
            if folder == "lang":
                raw += b"\0"
            names.append(name)
            c.write("extern const unsigned char %s[]; extern const unsigned int %s_size;\n" % (name, name))
            c.write("const unsigned char %s[] = {%s};\nconst unsigned int %s_size = %d;\n" % (name, ",".join(str(b) for b in raw), name, len(raw)))
for name in names:
    with open(os.path.join(out, "stubs", name + ".h"), "w") as h:
        h.write("#pragma once\nextern const unsigned char %s[];\nextern const unsigned int %s_size;\n" % (name, name))
